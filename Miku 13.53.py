

# Словарь химических элементов
elements = {
    "медь": "Cu",
    "кислород": "O",
    "водород": "H",
    "железо": "Fe",
    "золото": "Au"
}

# Ввод названия элемента
name = input("Введите название элемента: ").strip().lower()

if name in elements:
    print(f"Обозначение: {elements[name]}")
else:
    print("Элемент не найден.")
