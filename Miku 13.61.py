

countries = {
    "Россия": {"столица": "Москва", "часть_света": "Европа/Азия", "население": 144.1, "площадь": 17098},
    "Германия": {"столица": "Берлин", "часть_света": "Европа", "население": 83.2, "площадь": 357},
    "Франция": {"столица": "Париж", "часть_света": "Европа", "население": 67.4, "площадь": 643},
    "Китай": {"столица": "Пекин", "часть_света": "Азия", "население": 1402.1, "площадь": 9597},
    "Япония": {"столица": "Токио", "часть_света": "Азия", "население": 125.8, "площадь": 377}
}

# 1) Столица по названию государства
country = input("Введите название государства: ").strip()
if country in countries:
    print(f"Столица: {countries[country]['столица']}")
else:
    print("Государство не найдено.")

# 2) Название государства по столице
capital = input("Введите столицу: ").strip()
found = False
for ctry, info in countries.items():
    if info["столица"] == capital:
        print(f"Государство: {ctry}")
        found = True
        break
if not found:
    print("Столица не найдена.")

# 3) Вся информация о заданном государстве
country = input("Введите государство для полной информации: ").strip()
if country in countries:
    info = countries[country]
    print(f"Столица: {info['столица']}")
    print(f"Часть света: {info['часть_света']}")
    print(f"Население: {info['население']} млн")
    print(f"Площадь: {info['площадь']} тыс. км²")
    density = info['население'] / info['площадь']
    print(f"Плотность населения: {density:.3f} млн/тыс. км²")
else:
    print("Государство не найдено.")

# 4) Названия всех стран в заданной части света
part = input("Введите часть света: ").strip()
print(f"Страны в части света '{part}':")
for ctry, info in countries.items():
    if part in info["часть_света"]:
        print(ctry)

# 5) Плотность населения для каждого государства
print("\nПлотность населения (млн/тыс. км²):")
for ctry, info in countries.items():
    density = info['население'] / info['площадь']
    print(f"{ctry}: {density:.3f}")

# 6) Количество государств в заданной части света
part = input("Введите часть света для подсчёта: ").strip()
count = 0
for info in countries.values():
    if part in info["часть_света"]:
        count += 1
print(f"Количество государств: {count}")

# 7) Общая площадь государств в заданной части света
part = input("Введите часть света для подсчёта площади: ").strip()
total_area = 0
for info in countries.values():
    if part in info["часть_света"]:
        total_area += info['площадь']
print(f"Общая площадь: {total_area} тыс. км²")
